// Optional shared-password gate for installs reachable by other people (set APP_PASSWORD).
// Web Crypto only: this runs in the proxy as well as in server actions.

export const SESSION_COOKIE = "kl_session";

/** The session token is an HMAC of a fixed label with the password, so changing APP_PASSWORD signs everyone out. */
export async function sessionToken(password: string): Promise<string> {
  const key = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  const sig = await crypto.subtle.sign("HMAC", key, new TextEncoder().encode("kustomlearn-session-v1"));
  return Array.from(new Uint8Array(sig), (b) => b.toString(16).padStart(2, "0")).join("");
}

/** Constant-time string comparison. */
export function safeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}
